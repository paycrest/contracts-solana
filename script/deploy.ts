import { execSync } from "child_process";
import * as fs from "fs";
import * as os from "os";
import * as path from "path";
import { PublicKey, SystemProgram, TransactionInstruction } from "@solana/web3.js";
import {
  assertEnvironment,
  confirmContinue,
  encodeInitialize,
  findConfigPda,
  getConnection,
  getDeployerKeypair,
  getExplorerUrl,
  getAccountExplorerUrl,
  sendAndConfirm,
  updateConfigFile,
} from "./utils";
import { getNetworkConfig } from "./config";
import dotenv from "dotenv";

dotenv.config();

const network = process.argv[2] || "devnet";

assertEnvironment();

const SO_PATH = path.join(__dirname, "../target/deploy/paycrest_gateway.so");
const KEYPAIR_PATH = path.join(__dirname, "../target/deploy/paycrest_gateway-keypair.json");

async function deployGateway() {
  console.log("\n=== Deploying Paycrest Gateway to Solana ===");
  console.log(`Network: ${network}\n`);

  const networkConfig = getNetworkConfig(network);
  const deployer = getDeployerKeypair();

  if (!fs.existsSync(SO_PATH)) {
    throw new Error(
      `Program binary not found at ${SO_PATH}. Run 'cargo-build-sbf --manifest-path program/Cargo.toml' first.`
    );
  }
  if (!fs.existsSync(KEYPAIR_PATH)) {
    throw new Error(
      `Program keypair not found at ${KEYPAIR_PATH}. It is generated by cargo-build-sbf on first build.`
    );
  }

  const programKeypairBytes = JSON.parse(fs.readFileSync(KEYPAIR_PATH, "utf-8"));
  const programId = new PublicKey(
    Buffer.from(programKeypairBytes).subarray(32) // solana-keygen layout: [secret(32) || pubkey(32)]
  );

  await confirmContinue({
    Network: network,
    RPC: networkConfig.rpcUrl,
    "Program Id": programId.toBase58(),
    "Deployer Address": deployer.publicKey.toBase58(),
    "Treasury Address": process.env.TREASURY_ADDRESS,
    "Aggregator Address": process.env.AGGREGATOR_ADDRESS,
    "Chain Id (synthetic, D3/O2)": networkConfig.chainId,
  });

  // -- 1. Upload the program binary via the Solana CLI --
  // (Buffer-write + finalize is a multi-transaction dance the CLI already
  // handles correctly; there is no value in reimplementing it over the JS
  // RPC client.) The deployer secret is already required in .env for step
  // 2 below; writing it to a private 0600 temp file for the CLI call is no
  // new exposure, and is safer/more portable than shell process
  // substitution.
  console.log("[1/3] Deploying program binary via `solana program deploy`...");
  const tempKeypairPath = path.join(os.tmpdir(), `paycrest-deployer-${Date.now()}.json`);
  fs.writeFileSync(tempKeypairPath, JSON.stringify(Array.from(deployer.secretKey)), { mode: 0o600 });
  try {
    const deployCommand = [
      "solana program deploy",
      `"${SO_PATH}"`,
      `--program-id "${KEYPAIR_PATH}"`,
      `--url "${networkConfig.rpcUrl}"`,
      `--keypair "${tempKeypairPath}"`,
    ].join(" ");
    execSync(deployCommand, { stdio: "inherit" });
  } finally {
    fs.rmSync(tempKeypairPath, { force: true });
  }
  console.log(`   Program deployed: ${programId.toBase58()}`);
  console.log(`   Explorer: ${getAccountExplorerUrl(network, programId.toBase58())}`);

  // -- 2. Initialize Config (D3: write-once chain_id, sets owner) --
  console.log("\n[2/3] Initializing Config PDA...");
  const [configPda, bump] = findConfigPda(programId);
  console.log(`   Config PDA: ${configPda.toBase58()} (bump ${bump})`);

  const initIx = new TransactionInstruction({
    programId,
    keys: [
      { pubkey: deployer.publicKey, isSigner: true, isWritable: true },
      { pubkey: configPda, isSigner: false, isWritable: true },
      { pubkey: SystemProgram.programId, isSigner: false, isWritable: false },
    ],
    data: encodeInitialize(bump, networkConfig.chainId),
  });

  const connection = getConnection(network);
  await sendAndConfirm(connection, network, initIx, deployer);
  console.log("   Config initialized.");

  // -- 3. Persist the program id to config.ts --
  console.log("\n[3/3] Updating config.ts...");
  await updateConfigFile(network, programId.toBase58());

  console.log("\n=== Gateway deployed successfully! ===");
  console.log(`   Program Id: ${programId.toBase58()}`);
  console.log(`   Config PDA: ${configPda.toBase58()}`);

  console.log("\n=== Next steps ===");
  console.log("   1. Run 'npm run update-addresses' to set treasury and aggregator");
  console.log("   2. Run 'npm run set-tokens' to whitelist supported tokens");
  console.log("   3. Run 'npm run set-fee-settings' to configure token fee settings");
  console.log("   4. Run 'npm run check-status' to verify");

  return { programId: programId.toBase58(), configPda: configPda.toBase58() };
}

deployGateway()
  .then(() => {
    console.log("\n=== Deployment complete! ===");
    process.exit(0);
  })
  .catch((error) => {
    console.error("\n[ERROR] Deployment failed:", error);
    process.exit(1);
  });
